// Regenerate the backend's bundled assets for the Telegram apex-board pull
// card (backend/packages/api/src/modules/packs/pull-card.ts):
//
//   backend/.../api/admin/media/nekst-font-b64.ts   Nekst Black (display face)
//   backend/.../api/admin/media/geist-font-b64.ts   Geist Regular (body face)
//   backend/.../modules/packs/pull-card-assets.ts   tier frames + PSA logo
//
// Shipped as TS modules for the same reason as gen-arimo-font-module.mjs:
// `medusa build` does not copy binary src/ assets into the deployed bundle, and
// the backend's Docker build context (backend/) has no storefront public/.
//
// Nekst ships to the storefront as WOFF2 only, and sharp's prebuilt FreeType
// has no brotli, so a WOFF2 silently falls back to another face. Decompress it
// to TTF first and pass that path in:
//
//   pip install fonttools brotli
//   fonttools ttLib.woff2 decompress public/fonts/Nekst-Black.woff2 -o <tmp>/Nekst-Black.ttf
//   node scripts/gen-pull-card-assets.mjs <tmp>/Nekst-Black.ttf
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const nekstTtf = process.argv[2];
if (!nekstTtf || !nekstTtf.toLowerCase().endsWith('.ttf')) {
  console.error(
    'usage: node scripts/gen-pull-card-assets.mjs <Nekst-Black.ttf>',
  );
  process.exit(1);
}

const api = path.join(root, 'backend', 'packages', 'api', 'src');
const b64 = (file) => readFileSync(file).toString('base64');
const TIERS = [
  'immortal',
  'legendary',
  'mythical',
  'rare',
  'uncommon',
  'common',
];

const write = (out, body) => {
  writeFileSync(out, body);
  console.log(`wrote ${path.relative(root, out)} (${body.length} chars)`);
};

write(
  path.join(api, 'api', 'admin', 'media', 'nekst-font-b64.ts'),
  '// GENERATED by scripts/gen-pull-card-assets.mjs — do not edit by hand.\n' +
    '// Base64 of public/fonts/Nekst-Black.woff2 decompressed to TTF (Nekst\n' +
    '// Black, Copyright (c) 2020 Denis Serebryakov) — the storefront display\n' +
    '// face, rendered server-side into the Telegram apex-board pull card.\n' +
    '// eslint-disable-next-line max-len\n' +
    `export const NEKST_FONT_B64 =\n  '${b64(nekstTtf)}';\n`,
);

write(
  path.join(api, 'api', 'admin', 'media', 'geist-font-b64.ts'),
  '// GENERATED by scripts/gen-pull-card-assets.mjs — do not edit by hand.\n' +
    '// Base64 of Geist-Regular.ttf as shipped in next/dist/compiled/@vercel/og\n' +
    '// (Geist, SIL Open Font License 1.1 — Copyright 2024 The Geist Project\n' +
    '// Authors, https://github.com/vercel/geist-font). The storefront body face.\n' +
    '// eslint-disable-next-line max-len\n' +
    `export const GEIST_FONT_B64 =\n  '${b64(
      path.join(
        root,
        'node_modules',
        'next',
        'dist',
        'compiled',
        '@vercel',
        'og',
        'Geist-Regular.ttf',
      ),
    )}';\n`,
);

const tierMap = (dir) =>
  '{\n' +
  TIERS.map(
    (t) =>
      `  ${t}:\n    '${b64(path.join(root, 'public', 'images', dir, `${t}.webp`))}',`,
  ).join('\n') +
  '\n}';

write(
  path.join(api, 'modules', 'packs', 'pull-card-assets.ts'),
  '// GENERATED by scripts/gen-pull-card-assets.mjs — do not edit by hand.\n' +
    '// Base64 copies of the storefront tier-frame art (public/images/slab-frames\n' +
    '// and raw-frames, keyed by lowercase tier), public/images/psa.png and the\n' +
    '// header logo (public/branding/polycards-logo.png), for the Telegram\n' +
    '// apex-board pull card. Re-run the script after the storefront frames or\n' +
    '// logo change so the channel keeps matching the site.\n' +
    '/* eslint-disable max-len */\n' +
    `export const SLAB_FRAME_B64: Record<string, string> = ${tierMap('slab-frames')};\n\n` +
    `export const RAW_FRAME_B64: Record<string, string> = ${tierMap('raw-frames')};\n\n` +
    `export const PSA_LOGO_B64 =\n  '${b64(path.join(root, 'public', 'images', 'psa.png'))}';\n\n` +
    `export const BRAND_LOGO_B64 =\n  '${b64(path.join(root, 'public', 'branding', 'polycards-logo.png'))}';\n`,
);
