// Regenerate backend/packages/api/src/api/admin/media/one-piece-reprints.ts:
// which booster each One Piece card code was REPRINTED in, by print kind
// (SP / Wanted / TR / manga / alt art / base), from Limitless TCG.
//
// Why: a PSA label's first line names the box a card came out of ("2024 ONE
// PIECE OP08 EN" for the Jewelry Bonney ST02-007 SP), but PriceCharting often
// files an SP / Wanted / TR reprint under the card's ORIGINAL set ("Starter
// Deck 2"). Limitless lists every print of a code with its box and kind.
//
// Run when a new One Piece booster is out:  node scripts/one-piece-reprints.mjs
// It only reads public pages (about 450 requests, paced), then rewrites the
// data file; review the diff before committing.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const BASE = 'https://onepiece.limitlesstcg.com/cards';
const UA = { 'user-agent': 'Mozilla/5.0 (compatible; Polycards label data)' };
const OUT = join(
  import.meta.dirname,
  '..',
  'backend/packages/api/src/api/admin/media/one-piece-reprints.ts',
);
const pause = () => new Promise((r) => setTimeout(r, 300));
const get = async (path) =>
  (await fetch(`${BASE}${path}`, { headers: UA })).text();

// Booster product pages. The slug's first token is the product code.
const sets = await get('');
const slugs = [
  ...new Set(
    [...sets.matchAll(/href="\/cards\/((?:op|eb|prb)\d{2}-[a-z0-9-]+)"/g)].map(
      (m) => m[1],
    ),
  ),
];

// Limitless set name (as on a card page's prints table) -> product code.
const PRODUCT = {};
for (const slug of slugs) {
  const html = await get(`/${slug}`);
  // "<title>Two Legends (OP08) – Limitless One Piece</title>" -> "two legends"
  const title = html
    .match(/<title>([^<]+?)\s*(?:\([^)]*\))?\s*–/)?.[1]
    ?.trim()
    .toLowerCase();
  if (title)
    PRODUCT[title.replace(/&#0?39;/g, "'")] = slug.split('-')[0].toUpperCase();
  await pause();
}

// Every code a booster lists that isn't its own: a reprint.
const reprinted = new Set();
for (const slug of slugs) {
  const product = slug.split('-')[0].toUpperCase();
  const html = await get(`/${slug}`);
  for (const m of html.matchAll(
    /href="\/cards\/([A-Za-z]{1,3}\d{2}-\d{3})(?:\?v=\d+)?"/g,
  )) {
    const code = m[1].toUpperCase();
    if (!code.startsWith(`${product}-`)) reprinted.add(code);
  }
  await pause();
}

const kindOf = (slug, tag) => {
  if (/-sp(-gold|-silver)?$/.test(slug) || /-sp-/.test(slug)) return 'sp';
  if (/wanted/.test(slug) || tag === 'wanted') return 'wanted';
  if (/manga/.test(slug) || tag === 'manga') return 'manga';
  if (/treasure|-tr$/.test(slug) || tag === 'tr') return 'tr';
  if (/alternate-art|parallel/.test(slug) || tag === 'aa') return 'aa';
  return 'base';
};

const data = {};
for (const code of [...reprinted].sort()) {
  const html = await get(`/${code}`);
  const own = code.split('-')[0];
  const map = {};
  for (const m of html.matchAll(
    /<a\s+href="\/cards\/[^"?]+(?:\?v=\d+)?"\s*>\s*([^<]+?)\s*<span class="prints-table-card-number">([^<]*)<\/span>[\s\S]*?(?:tcgplayer\.com%2Fproduct%2F\d+%2F([a-z0-9-]+)|<\/tr>)/g,
  )) {
    const set = m[1]
      .replace(/&#0?39;/g, "'")
      .replace(/&amp;/g, '&')
      .trim()
      .toLowerCase();
    const product = PRODUCT[set];
    // The card's own box is kept too: an own-box print of the same kind makes
    // the reprint ambiguous, and the label then trusts PriceCharting's set.
    if (!product) continue;
    const kind = kindOf(m[3] ?? '', (m[2] ?? '').trim());
    (map[kind] ??= new Set()).add(product);
  }
  if (Object.values(map).some((s) => [...s].some((p) => p !== own))) {
    data[code] = Object.fromEntries(
      Object.entries(map).map(([k, s]) => [k, [...s].sort()]),
    );
  }
  await pause();
}

const rows = Object.entries(data)
  .map(
    ([code, map]) =>
      `  '${code}': ${JSON.stringify(map)
        .replace(/"/g, "'")
        .replace(/'(\w+)':/g, '$1: ')},`,
  )
  .join('\n');
writeFileSync(
  OUT,
  `// GENERATED by scripts/one-piece-reprints.mjs from ${BASE} on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand — rerun the script. For each One Piece card code, the
// boosters that REPRINTED it, by print kind (sp, wanted, tr, manga, aa, base).
// The card's own set is listed too when it has that kind. Read by
// one-piece-label.ts.

export type ReprintKind = 'sp' | 'wanted' | 'tr' | 'manga' | 'aa' | 'base';

export const ONE_PIECE_REPRINTS: Record<
  string,
  Partial<Record<ReprintKind, readonly string[]>>
> = {
${rows}
};
`,
);
console.log(`${Object.keys(data).length} reprinted codes -> ${OUT}`);
